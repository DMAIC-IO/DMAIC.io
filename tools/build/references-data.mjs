/**
 * references-data — generate js/core/references-registry.generated.js.
 *
 * Scans js/modules/<id>/<id>-references.js and emits EAGER static imports of
 * every module reference list, keyed by module id (the directory name). Eager
 * (not dynamic import()) so esbuild compiles all references into app.min.js.
 * Mirrors help-data.mjs.
 */
import { readdirSync, existsSync, statSync } from 'node:fs';
import { join } from 'node:path';

const MODULES_DIR = 'js/modules';

/** @param {string} appDir @returns {string[]} sorted ids with `<id>-references.js`. */
export function collectReferenceIds(appDir) {
  const root = join(appDir, MODULES_DIR);
  const ids = [];
  for (const name of readdirSync(root)) {
    const dir = join(root, name);
    if (!statSync(dir).isDirectory()) continue;
    if (existsSync(join(dir, `${name}-references.js`))) ids.push(name);
  }
  return ids.sort();
}

/**
 * Render the generated registry module source.
 * @param {string[]} ids
 * @returns {string}
 */
export function renderReferencesRegistryModule(ids) {
  const imports = ids
    .map((id, i) => `import r${i} from '../modules/${id}/${id}-references.js';`)
    .join('\n');
  const entries = ids
    .map((id, i) => `  ${JSON.stringify(id)}: r${i}`)
    .join(',\n');
  return `// AUTO-GENERATED by tools/build/references-data.mjs — do not edit.
${imports}

export const REFS = {
${entries}${entries ? ',' : ''}
};
`;
}

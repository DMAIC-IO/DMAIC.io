/**
 * glossary-data — generate js/core/glossary-data.generated.js.
 *
 * Inlines glossary/index.json (catalog) and every referenced term file into
 * one module so the runtime glossary registry reads bundled data instead of
 * fetching JSON at runtime. Mirrors lab-data.mjs / help-data.mjs.
 */
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const GLOSSARY_DIR = 'glossary';

/** @returns {{catalog:object, terms:Object<string,object>}} */
export function collectGlossaryData(appDir) {
  const root = join(appDir, GLOSSARY_DIR);
  const catalog = JSON.parse(readFileSync(join(root, 'index.json'), 'utf8'));
  const terms = {};
  for (const idx of (Array.isArray(catalog.terms) ? catalog.terms : [])) {
    const p = join(root, idx.file);
    if (!existsSync(p)) continue;   // tolerate index entries without a file
    terms[idx.id] = JSON.parse(readFileSync(p, 'utf8'));
  }
  return { catalog, terms };
}

export function renderGlossaryDataModule({ catalog, terms }) {
  return `// AUTO-GENERATED by tools/build/glossary-data.mjs — do not edit.
export const GLOSSARY_CATALOG = ${JSON.stringify(catalog)};
export const GLOSSARY_TERMS = ${JSON.stringify(terms)};
`;
}

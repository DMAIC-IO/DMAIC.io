/**
 * help-data — generate js/core/help-registry.generated.js.
 *
 * Scans `js/modules/<id>/<id>-help.js` and emits EAGER static imports of
 * every module handbook, keyed by id.
 *
 * Eager (not dynamic import()) so esbuild compiles all help content into
 * app.min.js — no runtime path resolution, no separate chunks. Mirrors
 * lab-data.mjs.
 */
import { readdirSync, existsSync, statSync } from 'node:fs';
import { join } from 'node:path';

const MODULES_DIR = 'js/modules';

/** @returns {string[]} sorted module ids that have a `<id>/<id>-help.js`. */
export function collectHelpIds(appDir) {
  const root = join(appDir, MODULES_DIR);
  const ids = [];
  for (const name of readdirSync(root)) {
    const dir = join(root, name);
    if (!statSync(dir).isDirectory()) continue;
    if (existsSync(join(dir, `${name}-help.js`)) || existsSync(join(dir, 'legacy', `${name}-help.js`))) ids.push(name);
  }
  return ids.sort();
}

/**
 * Render the generated registry module source.
 * @param {string[]} ids  module handbook ids
 * @param {string} [appDir]  app root; a handbook under `<id>/legacy/` is imported from there
 * @returns {string} the source of js/core/help-registry.generated.js
 */
export function renderHelpRegistryModule(ids, appDir) {
  const dirOf = (id) => (appDir && existsSync(join(appDir, MODULES_DIR, id, 'legacy', `${id}-help.js`)) ? `${id}/legacy` : id);
  const imports = ids.map((id, i) => `import h${i} from '../modules/${dirOf(id)}/${id}-help.js';`).join('\n');
  const entries = ids.map((id, i) => `  ${JSON.stringify(id)}: h${i}`).join(',\n');
  return `// AUTO-GENERATED by tools/build/help-data.mjs — do not edit.
${imports}

export const HELP = {
${entries},
};
`;
}

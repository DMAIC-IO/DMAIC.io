/**
 * help-data — generate js/core/help-registry.generated.js.
 *
 * Scans two places and emits EAGER static imports of every handbook, keyed
 * by id:
 *   js/modules/<id>/<id>-help.js   — the 72 module handbooks
 *   js/help/<id>-help.js           — module-free chapters (the AI-assistant
 *                                    briefing; a "Working with Qprovement"
 *                                    chapter would live here too)
 *
 * Eager (not dynamic import()) so esbuild compiles all help content into
 * app.min.js — no runtime path resolution, no separate chunks. Mirrors
 * lab-data.mjs.
 */
import { readdirSync, existsSync, statSync } from 'node:fs';
import { join } from 'node:path';

const MODULES_DIR = 'js/modules';
const GUIDES_DIR = 'js/help';
const HELP_SUFFIX = '-help.js';

/** @returns {string[]} sorted module ids that have a `<id>/<id>-help.js`. */
export function collectHelpIds(appDir) {
  const root = join(appDir, MODULES_DIR);
  const ids = [];
  for (const name of readdirSync(root)) {
    const dir = join(root, name);
    if (!statSync(dir).isDirectory()) continue;
    if (existsSync(join(dir, `${name}-help.js`))) ids.push(name);
  }
  return ids.sort();
}

/**
 * @param {string} appDir  app root (the directory holding `js/`)
 * @returns {string[]} sorted ids of module-free handbooks in `js/help`,
 *   i.e. every `<id>-help.js` there. Missing directory → empty list: the
 *   place must not become a precondition.
 */
export function collectGuideIds(appDir) {
  const root = join(appDir, GUIDES_DIR);
  if (!existsSync(root)) return [];
  return readdirSync(root)
    .filter(name => name.endsWith(HELP_SUFFIX))
    .map(name => name.slice(0, -HELP_SUFFIX.length))
    .sort();
}

/**
 * Render the generated registry module source.
 * @param {string[]} ids  module handbook ids
 * @param {string[]} [guideIds]  module-free handbook ids
 * @returns {string} the source of js/core/help-registry.generated.js
 */
export function renderHelpRegistryModule(ids, guideIds = []) {
  const imports = [
    ...ids.map((id, i) => `import h${i} from '../modules/${id}/${id}-help.js';`),
    ...guideIds.map((id, i) => `import g${i} from '../help/${id}-help.js';`),
  ].join('\n');
  const entries = [
    ...ids.map((id, i) => `  ${JSON.stringify(id)}: h${i}`),
    ...guideIds.map((id, i) => `  ${JSON.stringify(id)}: g${i}`),
  ].join(',\n');
  return `// AUTO-GENERATED by tools/build/help-data.mjs — do not edit.
${imports}

export const HELP = {
${entries},
};
`;
}

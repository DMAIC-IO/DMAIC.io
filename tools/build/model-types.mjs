/**
 * D.Mike — Typen aus dem Model-Schema (model-types.mjs)
 *
 * Schreibt je Modul mit deklarativem Model `js/modules/<id>/domain/model.types.js`:
 * JSDoc-Typedefs für Felder, Ansichtsfelder, Kommando-Objekte und das Model,
 * geprüft von `tsc --checkJs --noEmit`. Kein TypeScript im Repo.
 *
 * Ebenso je Modul mit `viewmodel/state.js` (UI-State aus `defineState`)
 * `viewmodel/state.types.js`: der State-Typ und der Alias `<Id>ViewFn` für
 * den `view`-Block (`this` getypt über `ThisType`).
 *
 * Der Generator IMPORTIERT `domain/model.js` in Node, statt den Quelltext zu
 * analysieren — bewusst gegen die sonstige Regel „der Build importiert nicht
 * aus js/“ (core/view-fields.js): `domain/` ist frei von DOM, Alpine und
 * Kontext, `core/model.js` ist rein, und so gilt für Typen und `describe`
 * derselbe Typtext (`describeType`).
 */
import { existsSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { describeType } from '../../js/core/model.js';

/**
 * Alle Module mit `domain/model.js`, nach Id sortiert.
 * @param {string} appDir Wurzel von app/dev
 * @returns {{ id: string, file: string }[]}
 */
export function collectModelFiles(appDir) {
  const root = join(appDir, 'js', 'modules');
  if (!existsSync(root)) return [];
  return readdirSync(root).sort()
    .map(id => ({ id, file: join(root, id, 'domain', 'model.js') }))
    .filter(({ file }) => existsSync(file));
}

/**
 * Den einen Export mit Schema laden. Der Zeitstempel im Query hält den
 * Import im Watch-Modus frisch (nur für diese Datei, nicht für ihre Importe).
 * @param {string} file
 * @returns {Promise<{ name: string, schema: object }>}
 */
export async function loadModelSchema(file) {
  const mod = await import(`${pathToFileURL(file).href}?v=${statSync(file).mtimeMs}`);
  const hits = Object.entries(mod).filter(([, v]) => typeof v === 'function' && v.schema?.fields);
  if (hits.length !== 1) {
    throw new Error(`${file}: erwartet genau einen Export mit Schema (defineModel), gefunden ${hits.length}`);
  }
  return { name: hits[0][0], schema: hits[0][1].schema };
}

const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);

/** @param {string} name @param {Record<string, object>} specs @returns {string[]} */
function typedef(name, specs) {
  const out = ['/**', ` * @typedef {object} ${name}`];
  for (const [k, s] of Object.entries(specs)) {
    out.push(` * @property {${describeType(s)}} ${s.optional === true ? `[${k}]` : k}`);
  }
  out.push(' */', '');
  return out;
}

/**
 * Der Inhalt von `domain/model.types.js`.
 * @param {{ name: string, schema: { fields: object, view: object, commands: object } }} model
 * @returns {string}
 */
export function renderModelTypes({ name, schema }) {
  const cmds = Object.entries(schema.commands);
  const lines = [
    '// AUTO-GENERATED by tools/build/model-types.mjs — do not edit.',
    `// Quelle: domain/model.js (${name}). Geprüft mit tsc --checkJs.`,
    '',
    ...typedef(`${name}Fields`, schema.fields),
    ...typedef(`${name}View`, schema.view),
  ];
  for (const [cmd, def] of cmds) lines.push(...typedef(`${pascal(cmd)}Command`, def.params));
  const exec = cmds.length
    ? cmds.map(([cmd]) => `({ type: '${cmd}' } & ${pascal(cmd)}Command)`).join(' | ')
    : 'never';
  lines.push(
    '/**',
    ` * @typedef {${name}Fields & ${name}View & {`,
    ...cmds.map(([cmd, def]) => ` *   ${cmd}(cmd: ${pascal(cmd)}Command): ${def.returns ? describeType(def.returns) : 'void'},`),
    ` *   execute(cmd: ${exec}): unknown,`,
    ' *   toJSON(): object,',
    ' *   hasContent(): boolean,',
    ` * }} ${name}Model`,
    ' */',
    '',
    'export {};',
    '',
  );
  return lines.join('\n');
}

/**
 * Alle Module mit `viewmodel/state.js`, nach Id sortiert.
 * @param {string} appDir Wurzel von app/dev
 * @returns {{ id: string, file: string }[]}
 */
export function collectStateFiles(appDir) {
  const root = join(appDir, 'js', 'modules');
  if (!existsSync(root)) return [];
  return readdirSync(root).sort()
    .map(id => ({ id, file: join(root, id, 'viewmodel', 'state.js') }))
    .filter(({ file }) => existsSync(file));
}

/**
 * Den einen Export aus `defineState` laden (Objekt mit `schema.fields` und `create`).
 * @param {string} file
 * @returns {Promise<{ name: string, schema: { fields: object } }>}
 */
export async function loadStateSchema(file) {
  const mod = await import(`${pathToFileURL(file).href}?v=${statSync(file).mtimeMs}`);
  const hits = Object.entries(mod)
    .filter(([, v]) => v !== null && typeof v === 'object' && v.schema?.fields && typeof v.create === 'function');
  if (hits.length !== 1) {
    throw new Error(`${file}: erwartet genau einen Export mit Schema (defineState), gefunden ${hits.length}`);
  }
  return { name: hits[0][0], schema: hits[0][1].schema };
}

/** @param {string} id Modul-Id in kebab-case @returns {string} PascalCase */
const pascalId = (id) => id.split('-').map(pascal).join('');

/**
 * Typ-Import für den erzeugten Text. Der Pfad gilt relativ zur erzeugten Datei,
 * nicht zu diesem Skript; zusammengesetzt, damit der Grenz-Scanner ihn nicht
 * als echten Import dieser Datei liest.
 * @param {string} path
 * @returns {string}
 */
const typeImport = (path) => 'import' + `('${path}')`;

/**
 * Der Inhalt von `viewmodel/state.types.js`.
 * @param {{ id: string, name: string, schema: { fields: object }, modelName: string }} state
 *   `modelName`: Name des Model-Exports in `domain/model.js`
 * @returns {string}
 */
export function renderStateTypes({ id, name, schema, modelName }) {
  return [
    '// AUTO-GENERATED by tools/build/model-types.mjs — do not edit.',
    `// Quelle: viewmodel/state.js (${name}). Geprüft mit tsc --checkJs.`,
    '',
    ...typedef(name, schema.fields),
    '/**',
    ` * @typedef {${typeImport('../../../core/template-module.js')}.ViewFn<${typeImport('../domain/model.types.js')}.${modelName}Model, ${name}>} ${pascalId(id)}ViewFn`,
    ' */',
    '',
    'export {};',
    '',
  ].join('\n');
}

/**
 * Den einen Export aus `defineState` laden (Objekt mit `schema.fields` und `create`).
 * @param {string} file
 * @returns {Promise<{ name: string, schema: { fields: object } }>}
 */
export async function loadStateSchema(file) {
  const mod = await import(`${pathToFileURL(file).href}?v=${statSync(file).mtimeMs}`);
  const hits = Object.entries(mod)
    .filter(([, v]) => v !== null && typeof v === 'object' && v.schema?.fields && typeof v.create === 'function');
  if (hits.length !== 1) {
    throw new Error(`${file}: erwartet genau einen Export mit Schema (defineState), gefunden ${hits.length}`);
  }
  return { name: hits[0][0], schema: hits[0][1].schema };
}

/** @param {string} id Modul-Id in kebab-case @returns {string} PascalCase */
const pascalId = (id) => id.split('-').map(pascal).join('');

/**
 * Typ-Import für den erzeugten Text. Der Pfad gilt relativ zur erzeugten Datei,
 * nicht zu diesem Skript; zusammengesetzt, damit der Grenz-Scanner ihn nicht
 * als echten Import dieser Datei liest.
 * @param {string} path
 * @returns {string}
 */
const typeImport = (path) => 'import' + `('${path}')`;

/**
 * Der Inhalt von `viewmodel/state.types.js`.
 * @param {{ id: string, name: string, schema: { fields: object }, modelName: string }} state
 *   `modelName`: Name des Model-Exports in `domain/model.js`
 * @returns {string}
 */
export function renderStateTypes({ id, name, schema, modelName }) {
  return [
    '// AUTO-GENERATED by tools/build/model-types.mjs — do not edit.',
    `// Quelle: viewmodel/state.js (${name}). Geprüft mit tsc --checkJs.`,
    '',
    ...typedef(name, schema.fields),
    '/**',
    ` * @typedef {${typeImport('../../../core/template-module.js')}.ViewFn<${typeImport('../domain/model.types.js')}.${modelName}Model, ${name}>} ${pascalId(id)}ViewFn`,
    ' */',
    '',
    '/**',
    ` * @typedef {${typeImport('../../../core/template-module.js')}.ExportsDef<${typeImport('../domain/model.types.js')}.${modelName}Model, ${name}>} ${pascalId(id)}Exports`,
    ' */',
    '',
    'export {};',
    '',
  ].join('\n');
}


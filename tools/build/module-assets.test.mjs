/**
 * Templates und CSS je umgestelltem Modul (tools/build/module-assets.mjs).
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, readdirSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { renderModuleTemplates, writeModuleTemplates, moduleCss, writeModuleStyles, linkedModuleCss, collectModuleResources, buildModuleResourcesBlock, moduleResourceUrls } from './module-assets.mjs';
import { renderIndexHtml } from '../build-templates/build.mjs';

/** Temp-App aus `{ pfad: inhalt }`. */
function appWith(files) {
  const root = mkdtempSync(join(tmpdir(), 'module-assets-'));
  for (const [path, body] of Object.entries(files)) {
    const full = join(root, path);
    mkdirSync(join(full, '..'), { recursive: true });
    writeFileSync(full, body);
  }
  return root;
}

const DIST = '<html><body>\n<!-- TEMPLATES:START (generated by tools/build-templates) -->\n<!-- TEMPLATES:END -->\n</body></html>\n';

const TPL_APP = {
  'index.dist.html': DIST,
  'js/core/shared/box.part.html': '<!-- Doku -->\n<div class="box"></div>',
  'js/modules/alt/alt.html': '<section x-data="alt"></section>',
  'js/modules/neu/resources/view.html': '<section x-data="neu">\n  <!-- @include js/core/shared/box.part.html -->\n</section>',
  'js/modules/neu/resources/tile.html': '<div class="neu-tile" x-text="value"></div>',
  'js/modules/neu/resources/rows.part.html': '<tr></tr>',
};

test('renderModuleTemplates: view.html und tile.html mit Hülle, Partials aufgelöst', () => {
  const root = appWith(TPL_APP);
  const out = renderModuleTemplates(root, 'neu');
  assert.equal(out, [
    '<template data-tpl="js/modules/neu/resources/tile.html"><div class="neu-tile" x-text="value"></div></template>',
    '<template data-tpl="js/modules/neu/resources/view.html"><section x-data="neu">\n  <div class="box"></div>\n</section></template>',
    '',
  ].join('\n'));
});

test('renderModuleTemplates: Partials werden nicht einzeln ausgegeben', () => {
  const root = appWith(TPL_APP);
  assert.doesNotMatch(renderModuleTemplates(root, 'neu'), /rows\.part\.html/);
});

test('renderModuleTemplates: <script> ist ein Build-Fehler', () => {
  const root = appWith({ ...TPL_APP, 'js/modules/neu/resources/view.html': '<div><script>x()</script></div>' });
  assert.throws(() => renderModuleTemplates(root, 'neu'), /script/i);
});

test('renderIndexHtml bettet resources/ umgestellter Module nicht ein', () => {
  const root = appWith(TPL_APP);
  const html = renderIndexHtml(root, { converted: ['neu'] });
  assert.match(html, /data-tpl="js\/modules\/alt\/alt\.html"/);
  assert.doesNotMatch(html, /js\/modules\/neu\/resources\//);
  const all = renderIndexHtml(root, { converted: [] });
  assert.match(all, /data-tpl="js\/modules\/neu\/resources\/view\.html"/);
});

test('writeModuleTemplates schreibt js/chunks/templates/<id>-<hash8>.html und räumt auf', () => {
  const root = appWith(TPL_APP);
  mkdirSync(join(root, 'js', 'chunks', 'templates'), { recursive: true });
  writeFileSync(join(root, 'js', 'chunks', 'templates', 'neu-00000000.html'), 'alt');
  const urls = writeModuleTemplates(root, ['neu']);
  assert.match(urls.neu, /^js\/chunks\/templates\/neu-[0-9a-f]{8}\.html$/);
  assert.equal(readFileSync(join(root, ...urls.neu.split('/')), 'utf8'), renderModuleTemplates(root, 'neu'));
  assert.deepEqual(readdirSync(join(root, 'js', 'chunks', 'templates')), [urls.neu.split('/').pop()]);
});

test('writeModuleTemplates ohne umgestellte Module: leeres Ergebnis, kein Ordner nötig', () => {
  const root = appWith(TPL_APP);
  assert.deepEqual(writeModuleTemplates(root, []), {});
  assert.equal(existsSync(join(root, 'js', 'chunks', 'templates')), false);
});

test('erzeugte Dateien in js/chunks/ werden nie als Template-Quelle gesammelt', () => {
  const root = appWith(TPL_APP);
  writeModuleTemplates(root, ['neu']);
  assert.doesNotMatch(renderIndexHtml(root, { converted: ['neu'] }), /js\/chunks\//);
  assert.doesNotMatch(renderModuleTemplates(root, 'neu'), /js\/chunks\//);
});

test('moduleCss: minifiziert, null ohne style.css', async () => {
  const root = appWith({ 'js/modules/neu/resources/style.css': '.module-neu__box {\n  color: var(--color-text);\n}\n' });
  assert.equal((await moduleCss(root, 'neu')).trim(), '.module-neu__box{color:var(--color-text)}');
  assert.equal(await moduleCss(appWith({}), 'neu'), null);
});

test('moduleCss: url( und @import sind Build-Fehler', async () => {
  const withUrl = appWith({ 'js/modules/neu/resources/style.css': '.a { background: url(x.png); }' });
  await assert.rejects(() => moduleCss(withUrl, 'neu'), /neu: resources\/style\.css: url\( und @import sind nicht erlaubt/);
  const withImport = appWith({ 'js/modules/neu/resources/style.css': '@import "x.css";' });
  await assert.rejects(() => moduleCss(withImport, 'neu'), /@import/);
});

test('writeModuleStyles schreibt js/chunks/styles/<id>-<hash8>.css, ohne style.css kein Eintrag', async () => {
  const root = appWith({
    'js/modules/neu/resources/style.css': '.a { color: red; }',
    'js/modules/leer/resources/view.html': '<div></div>',
  });
  const urls = await writeModuleStyles(root, ['leer', 'neu']);
  assert.deepEqual(Object.keys(urls), ['neu']);
  assert.match(urls.neu, /^js\/chunks\/styles\/neu-[0-9a-f]{8}\.css$/);
  assert.equal(readFileSync(join(root, ...urls.neu.split('/')), 'utf8'), await moduleCss(root, 'neu'));
});

test('linkedModuleCss: STYLES-Link auf ein umgestelltes Modul ist ein Befund', () => {
  assert.deepEqual(linkedModuleCss(['css/variables.css', 'js/modules/neu/neu.css', 'js/modules/alt/alt.css'], ['neu']),
    ['styles: neu: index.dist.html verlinkt js/modules/neu/neu.css — umgestellte Module laden ihr CSS selbst']);
  assert.deepEqual(linkedModuleCss(['js/modules/alt/alt.css'], ['neu']), []);
});

test('collectModuleResources: Templates, Style und Dateien mit ?v=', () => {
  const root = appWith({
    'js/modules/neu/resources/i18n/ui.de.json': '{"name":"Neu"}',
    'js/modules/neu/resources/i18n/help.de.json': '{}',
    'js/modules/neu/resources/data/references.json': '[]',
    'js/modules/neu/resources/examples/examples.json': '{"examples":[]}',
    'js/modules/neu/resources/examples/pizza.csv': 'a\n1\n',
    'js/modules/neu/resources/view.html': '<div></div>',
  });
  const res = collectModuleResources(root, ['neu'], {
    templates: { neu: 'js/chunks/templates/neu-11111111.html' },
    styles: { neu: 'js/chunks/styles/neu-22222222.css' },
  });
  assert.equal(res.neu.templates, 'js/chunks/templates/neu-11111111.html');
  assert.equal(res.neu.style, 'js/chunks/styles/neu-22222222.css');
  assert.deepEqual(Object.keys(res.neu.files).sort(),
    ['data/references.json', 'examples/examples.json', 'i18n/help.de.json', 'i18n/ui.de.json']);
  assert.match(res.neu.files['i18n/ui.de.json'], /^js\/modules\/neu\/resources\/i18n\/ui\.de\.json\?v=[0-9a-f]{8}$/);
});

test('collectModuleResources: ohne Style kein style-Schlüssel', () => {
  const root = appWith({ 'js/modules/neu/resources/view.html': '<div></div>' });
  const res = collectModuleResources(root, ['neu'], { templates: { neu: 't.html' }, styles: {} });
  assert.deepEqual(res, { neu: { templates: 't.html', files: {} } });
});

test('buildModuleResourcesBlock und moduleResourceUrls', () => {
  assert.equal(buildModuleResourcesBlock({}), '  <script type="application/json" id="module-resources">{}</script>');
  const res = { neu: { templates: 't.html', style: 's.css', files: { 'i18n/ui.de.json': 'u?v=1' } } };
  assert.deepEqual(moduleResourceUrls(res), ['s.css', 't.html', 'u?v=1']);
});

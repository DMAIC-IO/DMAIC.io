const HOOKS_SRC = `import { defineModel, command, text, index, list } from '${MODEL_URL}';
export const Doc = defineModel({
  fields: { items: list(text()) },
  commands: {
    setItem: command({
      params: { idx: index('items', { existing: true }), text: text() },
      current({ idx }) { return { text: this.items[idx] }; },
      run() {},
    }),
    removeItem: command({ params: { idx: index('items', { existing: true }) }, confirm() { return null; }, run() {} }),
    plain: command({ params: {}, run() {} }),
  },
});
`;

test('current und confirm: Typen für this und Argument, nur wo vorhanden', async () => {
  const root = appWith({ 'js/modules/neu/domain/model.js': HOOKS_SRC });
  const out = renderModelTypes(await loadModelSchema(collectModelFiles(root)[0].file));
  assert.match(out, / \* @typedef \{\(this: DocModel, fixed: Partial<SetItemCommand>\) => Partial<SetItemCommand>\} SetItemCurrent\n/);
  assert.match(out, / \* @typedef \{\(this: DocModel, args: RemoveItemCommand\) => \(\{ key: string, params\?: Record<string, unknown> \}\|null\)\} RemoveItemConfirm\n/);
  assert.doesNotMatch(out, /SetItemConfirm|RemoveItemCurrent|PlainCurrent|PlainConfirm/);
  assert.match(out, /\nexport \{\};\n$/);
});


/**
 * Typen aus dem Model-Schema (tools/build/model-types.mjs).
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { collectModelFiles, loadModelSchema, renderModelTypes, collectStateFiles, loadStateSchema, renderStateTypes, collectFormFiles, loadFormSchemas, renderFormTypes, collectSettingsFiles, loadSettingsSchema, renderSettingsTypes, renderWidgetProps, renderBindingCheck } from './model-types.mjs';
import { defineWidget, list, text, number } from '../../js/core/model.js';

const MODEL_URL = pathToFileURL(join(import.meta.dirname, '..', '..', 'js', 'core', 'model.js')).href;

const MODEL_SRC = `import { defineModel, command, text, number, oneOf, index, list, record, boolean } from '${MODEL_URL}';
const COLS = ['a', 'b'];
export const COL_KEYS = COLS;
export const State = defineModel({
  fields: { title: text(), alpha: number({ nullable: true, default: null }), columns: record(COLS, list(text())) },
  view: { mode: oneOf(['month', 'week']) },
  commands: {
    moveItem: command({
      params: { from: oneOf(COLS), idx: index('columns[from]'), note: text({ optional: true }) },
      returns: boolean(),
      run() { return true; },
    }),
  },
});
`;

function appWith(files) {
  const root = mkdtempSync(join(tmpdir(), 'model-types-'));
  for (const [path, body] of Object.entries(files)) {
    const full = join(root, path);
    mkdirSync(join(full, '..'), { recursive: true });
    writeFileSync(full, body);
  }
  return root;
}

test('findet nur Module mit domain/model.js', () => {
  const root = appWith({ 'js/modules/neu/domain/model.js': MODEL_SRC, 'js/modules/alt/alt.js': '' });
  assert.deepEqual(collectModelFiles(root).map(m => m.id), ['neu']);
});

test('lädt das Schema des einen Model-Exports', async () => {
  const root = appWith({ 'js/modules/neu/domain/model.js': MODEL_SRC });
  const { name, schema } = await loadModelSchema(collectModelFiles(root)[0].file);
  assert.equal(name, 'State');
  assert.deepEqual(Object.keys(schema.fields), ['title', 'alpha', 'columns']);
});

test('kein oder zwei Model-Exporte sind ein Fehler', async () => {
  const root = appWith({ 'js/modules/x/domain/model.js': 'export const A = 1;\n' });
  await assert.rejects(loadModelSchema(collectModelFiles(root)[0].file), /genau einen Export/);
});

test('rendert Felder, Ansicht, Kommandos und das Model', async () => {
  const root = appWith({ 'js/modules/neu/domain/model.js': MODEL_SRC });
  const out = renderModelTypes(await loadModelSchema(collectModelFiles(root)[0].file));
  assert.match(out, /^\/\/ AUTO-GENERATED by tools\/build\/model-types\.mjs — do not edit\./);
  assert.match(out, / \* @typedef \{object\} StateFields\n \* @property \{string\} title\n \* @property \{number\|null\} alpha\n \* @property \{Record<'a'\|'b', string\[\]>\} columns\n/);
  assert.match(out, / \* @typedef \{object\} StateView\n \* @property \{'month'\|'week'\} mode\n/);
  assert.match(out, / \* @typedef \{object\} MoveItemCommand\n \* @property \{'a'\|'b'\} from\n \* @property \{number\} idx\n \* @property \{string\} \[note\]\n/);
  assert.match(out, / \* {3}moveItem\(cmd: MoveItemCommand\): boolean,/);
  assert.match(out, / \* {3}execute\(cmd: \(\{ type: 'moveItem' \} & MoveItemCommand\)\): unknown,/);
  assert.match(out, / \* {3}readonly context: import\('\.\.\/\.\.\/\.\.\/core\/model\.js'\)\.ModelContext,\n \* \}\} StateModel\n/);
  assert.match(out, / \* \}\} StateModel\n/);
  assert.match(out, /\nexport \{\};\n$/);
});

test('leere Ansicht wird {{}}, nicht object (sonst ist das Model in JS ohne strict any)', async () => {
  const src = MODEL_SRC.replace("view: { mode: oneOf(['month', 'week']) },", 'view: {},');
  const root = appWith({ 'js/modules/neu/domain/model.js': src });
  const out = renderModelTypes(await loadModelSchema(collectModelFiles(root)[0].file));
  assert.match(out, / \* @typedef \{\{\}\} StateView\n \*\/\n/);
});


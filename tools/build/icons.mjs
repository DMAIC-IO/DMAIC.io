/**
 * icons.mjs — erzeugt aus der Proxy-Tabelle die CSS-Maskenregeln.
 *
 * Je Icon entstehen vier Regeln (md, xs, sm, lg). Sie unterscheiden sich nur in
 * der eingebackenen stroke-width: Lucide zeichnet 2px auf 24er-Raster, was bei
 * kleiner Darstellung optisch ausdünnt und bei 24px zu fett wirkt. Die
 * Reihenfolge base → xs → sm → lg ist bindend: alle vier Selektoren haben
 * dieselbe Spezifität, es gewinnt der spätere.
 *
 * Accent-Icons (Quelle enthält das Literal ACCENT) tragen eigene Farbe und laufen
 * als background-image statt als Maske — sie brauchen keine Größenvarianten, aber
 * je eine Regel für helles und dunkles Theme.
 */
import { parseSpec } from './icon-map.mjs';

/** Farbtokens aus css/variables.css — --color-accent je Theme. */
const ACCENT_COLORS = { light: '#0066cc', dark: '#4da3ff' };

/** Die vier Größenstufen. `cls: ''` ist die Standardgröße md (20px). */
export const SIZES = [
  { cls: '', strokeWidth: 2 },
  { cls: 'icon--xs', strokeWidth: 2.5 },
  { cls: 'icon--sm', strokeWidth: 2.25 },
  { cls: 'icon--lg', strokeWidth: 1.75 },
];

/**
 * @param {string} svg
 * @returns {string} einzeiliges SVG ohne Kommentare und ohne class-Attribut
 */
export function normalizeSvg(svg) {
  return svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\sclass="[^"]*"/g, '')
    .trim()
    .replace(/\s*\n\s*/g, ' ')
    .replace(/>\s+</g, '><')
    .replace(/\s{2,}/g, ' ')
    .replace(/\s+>/g, '>')
    .replace(/\s+\/>/g, '/>');
}

/**
 * @param {string} svg  normalisiertes SVG
 * @param {number} width
 * @returns {string} SVG mit umgeschriebener stroke-width im Wurzel-Tag
 */
export function restroke(svg, width) {
  const open = svg.match(/<svg[^>]*>/);
  if (!open) return svg;
  if (!/stroke-width="[^"]*"/.test(open[0])) return svg;
  const rewritten = open[0].replace(/stroke-width="[^"]*"/, `stroke-width="${width}"`);
  return svg.replace(open[0], rewritten);
}

/**
 * @param {string} svg
 * @returns {string}
 */
export function svgToDataUri(svg) {
  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}

/**
 * @param {Record<string,string>} map          semantischer Name -> "<source>:<file>"
 * @param {(src: {kind: string, file: string}) => string} readSource
 * @returns {string} vollständiger Inhalt von assets/icons/icons.css
 */
export function buildIconsCss(map, readSource) {
  let css = '/* GENERATED by tools/build-icons.mjs — do not edit by hand. */\n';
  for (const name of Object.keys(map).sort()) {
    const src = parseSpec(map[name]);
    let raw;
    try {
      raw = readSource(src);
    } catch (err) {
      throw new Error(`icon "${name}" -> ${map[name]}: ${err.message}`, { cause: err });
    }
    const svg = normalizeSvg(raw);
    if (svg.includes('ACCENT')) {
      const light = svgToDataUri(svg.replaceAll('ACCENT', ACCENT_COLORS.light));
      const dark = svgToDataUri(svg.replaceAll('ACCENT', ACCENT_COLORS.dark));
      css += `.icon[data-icon="${name}"]{--icon:url("${light}")}\n`;
      css += `[data-theme="dark"] .icon[data-icon="${name}"]{--icon:url("${dark}")}\n`;
      continue;
    }
    for (const { cls, strokeWidth } of SIZES) {
      const uri = svgToDataUri(restroke(svg, strokeWidth));
      const sel = cls ? `.${cls}[data-icon="${name}"]` : `.icon[data-icon="${name}"]`;
      css += `${sel}{--icon:url("${uri}")}\n`;
    }
  }
  return css;
}

#!/usr/bin/env node
// build-icon-sprite.mjs — compile assets/icons/src/*.svg into a stacked sprite.
// Each icon is laid out in a vertical stack; each icon+theme gets a <view> so it
// is addressable via <img src="sprite.svg#<name>-<theme>">. Run when icons change.
// Also emits assets/icons/icons.css — per-icon data-URI CSS masks, which is what
// the app actually uses to render icons (see css/components.css .icon).
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, basename } from 'node:path';

const SRC = join(import.meta.dirname, '../assets/icons/src');
const OUT = join(import.meta.dirname, '../assets/icons/sprite.svg');
const CELL = 100;                                            // per-icon viewBox cell
// Resolved foreground tokens from css/variables.css:
//   light: :root              --color-text-primary: #1d1d1f
//   dark : [data-theme="dark"] --color-text-primary: #f5f5f7
const THEME_COLORS = { light: '#1d1d1f', dark: '#f5f5f7' };
// Accent tokens (from css/variables.css --color-accent): used by raw thumbnail
// icons that bake the accent colour per theme. Source uses the literal "ACCENT".
const ACCENT_COLORS = { light: '#0066cc', dark: '#4da3ff' };

const files = readdirSync(SRC).filter(f => f.endsWith('.svg')).sort();
const themes = Object.keys(THEME_COLORS);
let defs = '', views = '', y = 0;

// Attributes handled explicitly on the sprite's nested <svg> (or irrelevant
// once nested); everything else on the source root <svg> is a presentation
// attribute (stroke, fill, stroke-width, stroke-linecap, …) that MUST be
// forwarded, otherwise strokes drop out and the baked color is lost.
const DROP_ROOT_ATTRS = new Set([
  'xmlns', 'xmlns:xlink', 'viewBox', 'width', 'height', 'x', 'y',
  'aria-hidden', 'focusable', 'class', 'id', 'role',
]);

for (const f of files) {
  const name = basename(f, '.svg');
  const raw = readFileSync(join(SRC, f), 'utf8');
  // grab the source root <svg ...> opening tag
  const open = (raw.match(/<svg[^>]*>/) || [])[0] || '<svg>';
  const vb = (open.match(/viewBox="([^"]+)"/) || [])[1] || '0 0 24 24';
  // forward all presentation attributes from the source root <svg>
  const rootAttrs = [...open.matchAll(/([\w:-]+)="([^"]*)"/g)]
    .filter(([, k]) => !DROP_ROOT_ATTRS.has(k))
    .map(([, k, v]) => `${k}="${v}"`)
    .join(' ');
  const attrStr = rootAttrs ? ` ${rootAttrs}` : '';
  const inner = raw.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  for (const theme of themes) {
    // rebake currentColor in BOTH the inner markup and the forwarded root attrs
    const colored = inner.replace(/currentColor/g, THEME_COLORS[theme]);
    const coloredAttrs = attrStr.replace(/currentColor/g, THEME_COLORS[theme]);
    // place this variant in its own row of the stack
    defs += `  <g transform="translate(0 ${y})"><svg viewBox="${vb}" width="${CELL}" height="${CELL}" x="0" y="0"${coloredAttrs}>${colored}</svg></g>\n`;
    views += `  <view id="${name}-${theme}" viewBox="0 ${y} ${CELL} ${CELL}"/>\n`;
    y += CELL;
  }
}

const out = `<svg xmlns="http://www.w3.org/2000/svg" width="${CELL}" height="${y}">\n${views}${defs}</svg>\n`;
writeFileSync(OUT, out);
console.log(`sprite.svg: ${files.length} icons × ${themes.length} themes -> ${OUT}`);

// ── Also emit a CSS mask map: each icon as an inline data-URI mask. ──
// Standard icons: colour is supplied by the consumer via `background-color` (see
// css/components.css .icon rule); the source SVG's own paint is irrelevant under an
// alpha mask, so we emit the source verbatim (currentColor → opaque black when
// rendered as an image).
// Accent icons: source SVG uses the literal token "ACCENT" as a colour placeholder.
// These get two rules — a base rule with the light accent baked in, and a
// [data-theme="dark"] override with the dark accent — so .icon--raw renders correctly
// in both themes without any JS theme subscription.
const CSS_OUT = join(import.meta.dirname, '../assets/icons/icons.css');
let css = '/* GENERATED by tools/build-icon-sprite.mjs — do not edit by hand. */\n';
for (const f of files) {
  const name = basename(f, '.svg');
  const min = readFileSync(join(SRC, f), 'utf8')
    .trim()
    .replace(/>\s+</g, '><')
    .replace(/\s{2,}/g, ' ');
  if (min.includes('ACCENT')) {
    // Raw accent icon: bake the light accent into --icon, override for dark.
    const light = `data:image/svg+xml,${encodeURIComponent(min.replaceAll('ACCENT', ACCENT_COLORS.light))}`;
    const dark = `data:image/svg+xml,${encodeURIComponent(min.replaceAll('ACCENT', ACCENT_COLORS.dark))}`;
    css += `.icon[data-icon="${name}"]{--icon:url("${light}")}\n`;
    css += `[data-theme="dark"] .icon[data-icon="${name}"]{--icon:url("${dark}")}\n`;
  } else {
    // Standard mask icon: colour supplied by the consumer via background-color.
    const uri = `data:image/svg+xml,${encodeURIComponent(min)}`;
    css += `.icon[data-icon="${name}"]{--icon:url("${uri}")}\n`;
  }
}
writeFileSync(CSS_OUT, css);
console.log(`icons.css: ${files.length} mask rules -> ${CSS_OUT}`);
